// Symbol golden of flutter_edge_ai's five public libraries.
//
// Resolves the EXPORT NAMESPACE of each library with package:analyzer and
// compares one `name kind modifiers` line per symbol with
// `test/public_surface/<library>.golden.txt`. A directive-level golden would
// miss a new public declaration in an already-exported file; this one does
// not. Any change to what an app or an engine package can name is therefore a
// visible diff in review.
//
// Regenerate after an intended change (refused when CI is set):
//   UPDATE_GOLDENS=1 flutter test test/public_surface/public_surface_test.dart
//
// Scope notes:
// - The analyzer sees the NATIVE branch of conditional exports. Web drift is
//   caught by the example's `flutter build web` / `--wasm` in CI.
// - Symbols re-exported from OTHER packages (genai.dart re-exports
//   package:genai_primitives) are summarised as one `* <package> re-exported`
//   line, so a version bump or a `pub downgrade` of that package does not
//   change our golden.
@TestOn('vm')
library;

import 'dart:io';

import 'package:analyzer/dart/analysis/analysis_context_collection.dart';
import 'package:analyzer/dart/analysis/results.dart';
import 'package:analyzer/dart/element/element.dart';
import 'package:flutter_test/flutter_test.dart';

const _libraries = [
  'flutter_edge_ai.dart',
  'engine.dart',
  'engine_io.dart',
  'engine_web.dart',
  'genai.dart',
];

const _ownPackage = 'package:flutter_edge_ai/';

void main() {
  final update = Platform.environment['UPDATE_GOLDENS'] == '1';
  // Regenerating on CI would make the check pass by definition.
  final onCi = (Platform.environment['CI'] ?? '').isNotEmpty;

  for (final library in _libraries) {
    test('$library export namespace matches its golden', () async {
      final namespace = await _exportNamespace(library);
      final actual = _render(library, namespace);
      final golden = File(
        'test/public_surface/${library.replaceAll('.dart', '')}.golden.txt',
      );
      if (update) {
        if (onCi) {
          fail(
            'UPDATE_GOLDENS=1 is refused while CI is set: a regenerated golden '
            'always matches. Regenerate locally and commit the reviewed diff.',
          );
        }
        golden.writeAsStringSync(actual);
        return;
      }
      expect(
        golden.existsSync(),
        isTrue,
        reason:
            'Missing ${golden.path}. Run with UPDATE_GOLDENS=1 to create it.',
      );
      final expected = golden.readAsStringSync();
      if (actual != expected) {
        fail(_describeDrift(library, expected, actual));
      }
    }, timeout: const Timeout(Duration(minutes: 5)));
  }

  test(
    'FlutterEdgeAiDesktop is in the app namespace (dartPluginClass)',
    () async {
      // pubspec.yaml registers `dartPluginClass: FlutterEdgeAiDesktop` for
      // macOS/Windows/Linux without a `dartFileName`, so Flutter's generated
      // registrant resolves it through package:flutter_edge_ai/flutter_edge_ai.dart.
      final namespace = await _exportNamespace('flutter_edge_ai.dart');
      final element = namespace['FlutterEdgeAiDesktop'];
      expect(element, isA<ClassElement>());
      final registerWith = (element! as ClassElement).getMethod('registerWith');
      expect(registerWith, isNotNull);
      expect(registerWith!.isStatic, isTrue);
    },
    timeout: const Timeout(Duration(minutes: 5)),
  );
}

AnalysisContextCollection? _collection;

AnalysisContextCollection _contexts() =>
    _collection ??= AnalysisContextCollection(
      includedPaths: [Directory.current.absolute.path],
      sdkPath: _dartSdkPath(),
    );

Future<Map<String, Element>> _exportNamespace(String library) async {
  final path = File('lib/$library').absolute.path;
  final result = await _contexts()
      .contextFor(path)
      .currentSession
      .getResolvedLibrary(path);
  if (result is! ResolvedLibraryResult) {
    throw StateError('Cannot resolve $path: $result');
  }
  final errors = result.units
      .expand((unit) => unit.diagnostics)
      .where((d) => d.severity.name == 'error')
      .toList();
  if (errors.isNotEmpty) {
    throw StateError('$library does not analyze cleanly: $errors');
  }
  return result.element.exportNamespace.definedNames2;
}

String _render(String library, Map<String, Element> namespace) {
  final lines = <String>[];
  final foreign = <String>{};
  namespace.forEach((name, element) {
    final uri = element.library?.uri.toString() ?? '';
    if (!uri.startsWith(_ownPackage)) {
      foreign.add('* ${uri.split('/').first} re-exported');
      return;
    }
    lines.add('$name ${_describe(element)}');
  });
  lines.sort();
  final golden = [
    '# Export namespace of package:flutter_edge_ai/$library',
    '# Generated by test/public_surface/public_surface_test.dart',
    '# (UPDATE_GOLDENS=1 regenerates). One line per symbol: name kind modifiers.',
    ...lines,
    ...(foreign.toList()..sort()),
  ];
  return '${golden.join('\n')}\n';
}

String _describe(Element element) {
  final modifiers = <String>[];
  final String kind;
  switch (element) {
    case ClassElement c:
      kind = 'class';
      if (c.isSealed) modifiers.add('sealed');
      if (c.isAbstract && !c.isSealed) modifiers.add('abstract');
      if (c.isBase) modifiers.add('base');
      if (c.isInterface) modifiers.add('interface');
      if (c.isFinal) modifiers.add('final');
      if (c.isMixinClass) modifiers.add('mixin');
    case EnumElement _:
      kind = 'enum';
    case MixinElement m:
      kind = 'mixin';
      if (m.isBase) modifiers.add('base');
    case ExtensionTypeElement _:
      kind = 'extension-type';
    case ExtensionElement _:
      kind = 'extension';
    case TypeAliasElement _:
      kind = 'typedef';
    case TopLevelFunctionElement _:
      kind = 'function';
    case GetterElement g when g.isOriginVariable:
      kind = 'variable';
      final variable = g.variable;
      if (variable is TopLevelVariableElement) {
        if (variable.isConst) modifiers.add('const');
        if (variable.isFinal && !variable.isConst) modifiers.add('final');
        if (variable.isLate) modifiers.add('late');
      }
    case GetterElement _:
      kind = 'getter';
    case SetterElement s:
      kind = s.isOriginVariable ? 'variable-setter' : 'setter';
    default:
      kind = element.kind.name.toLowerCase();
  }
  if (element.metadata.hasDeprecated) modifiers.add('deprecated');
  return modifiers.isEmpty ? kind : '$kind ${modifiers.join(' ')}';
}

String _describeDrift(String library, String expected, String actual) {
  Set<String> body(String text) =>
      text.split('\n').where((l) => l.isNotEmpty && !l.startsWith('#')).toSet();
  final before = body(expected);
  final after = body(actual);
  final added = after.difference(before).toList()..sort();
  final removed = before.difference(after).toList()..sort();
  return [
    'The export namespace of package:flutter_edge_ai/$library changed.',
    if (added.isNotEmpty) 'Added:\n${added.map((l) => '  + $l').join('\n')}',
    if (removed.isNotEmpty)
      'Removed:\n${removed.map((l) => '  - $l').join('\n')}',
    'If this is intended, regenerate the golden with UPDATE_GOLDENS=1 and '
        'review the diff.',
  ].join('\n');
}

/// The Dart SDK the analyzer should use. `flutter test` runs this file in
/// flutter_tester, whose executable is not inside a Dart SDK, so find the SDK
/// Flutter ships in `<flutter>/bin/cache/dart-sdk`.
String _dartSdkPath() {
  final candidates = <String>[
    if (Platform.environment['FLUTTER_ROOT'] case final root?)
      '$root/bin/cache/dart-sdk',
  ];
  var dir = File(Platform.resolvedExecutable).parent;
  for (var i = 0; i < 8; i++) {
    candidates
      ..add('${dir.path}/dart-sdk')
      ..add(dir.path);
    dir = dir.parent;
  }
  for (final candidate in candidates) {
    if (File('$candidate/version').existsSync() &&
        Directory('$candidate/lib/core').existsSync()) {
      return candidate;
    }
  }
  throw StateError(
    'No Dart SDK found near ${Platform.resolvedExecutable}; set FLUTTER_ROOT.',
  );
}
